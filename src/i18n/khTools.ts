/** Pattern-based strings that contain numbers or other dynamic parts. */
export function translateKhPattern(text: string): string | null {
  let m = text.match(/^Copy (.+)$/);
  if (m) {
    const rest = Object.prototype.hasOwnProperty.call(KH_TOOLS, m[1]) ? KH_TOOLS[m[1]] : m[1];
    return `ចម្លង ${rest}`;
  }
  m = text.match(/^Token expired (\d+)s ago$/);
  if (m) return `Token បានផុតកំណត់ ${m[1]} វិនាទីមុន`;
  m = text.match(/^Token valid — expires in (\d+)s$/);
  if (m) return `Token ត្រឹមត្រូវ — ផុតកំណត់ក្នុង ${m[1]} វិនាទី`;
  m = text.match(/^(\d+)s ago$/);
  if (m) return `${m[1]} វិនាទីមុន`;
  m = text.match(/^(\d+) UUIDs?$/);
  if (m) return `UUID ${m[1]}`;
  m = text.match(/^Show all (\d+)$/);
  if (m) return `បង្ហាញទាំង ${m[1]}`;
  return null;
}
